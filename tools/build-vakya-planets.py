#!/usr/bin/env python3
"""Builds js/data/vakya-planets.js from the mahavakya tables in docs/graha-sphuta-sources.md
(section C). Run from the repo root after editing those tables:
    python3 tools/build-vakya-planets.py
Row format in the md: `day rasi deg min corr [corr2] [note]`; rows whose value is `-`
(risings, settings) carry no longitude and are skipped."""
import re, json, sys

SRC, OUT = "docs/graha-sphuta-sources.md", "js/data/vakya-planets.js"

def num(tok):
    tok = tok.replace("+", "").rstrip("?")   # "?" marks a faint reading in the notes
    if "/" in tok:
        a, b = tok.split("/")
        return float(a) / float(b)
    return float(tok)

planets, cur = {}, None
for line in open(SRC, encoding="utf-8").read().split("\n"):
    m = re.match(r"# (\w+) mahavakyas", line)
    if m:
        cur = m.group(1).lower(); planets[cur] = []; continue
    if cur is None: continue
    if re.match(r"# end ", line):
        cur = None; continue
    if re.match(r"C\d+\s*$", line):
        assert int(line[1:]) == len(planets[cur]) + 1, (cur, line)
        planets[cur].append([]); continue
    t = line.split()
    if not t or not t[0].isdigit() or t[1] == "-": continue
    ncorr = 2 if cur == "venus" else 1
    day, r, d, mi = (int(x) for x in t[:4])
    assert r < 12 and d < 30 and mi < 60, (cur, line)
    row = [day, (r * 30 + d) * 60 + mi] + [num(x) for x in t[4:4 + ncorr]]
    rows = planets[cur][-1]
    assert not rows or day > rows[-1][0], (cur, line)
    rows.append(row)

assert sorted(planets) == ["jupiter", "mars", "mercury", "saturn", "venus"], sorted(planets)
fmt = lambda x: str(int(x)) if x == int(x) else str(x)
out = ["// GENERATED by tools/build-vakya-planets.py from docs/graha-sphuta-sources.md (section C).",
       "// Do not edit by hand: correct the md table and rebuild.",
       "// Vakyakarana mahavakyas: for each planet, one array per synodic cycle, flat rows of",
       "// [day in cycle, longitude in arcminutes, corrector] (Venus: two correctors, for a",
       "// positive and a negative total dhruva).",
       "(function (global) {", '  "use strict";',
       "  const VedicEngine = global.VedicEngine = global.VedicEngine || {};",
       "  VedicEngine.VakyaPlanets = {"]
for p in ["mars", "mercury", "jupiter", "venus", "saturn"]:
    out.append("    " + p + ": [")
    for rows in planets[p]:
        out.append("      [" + ",".join(fmt(x) for row in rows for x in row) + "],")
    out.append("    ],")
out += ["  };", '})(typeof window !== "undefined" ? window : globalThis);', ""]
open(OUT, "w", encoding="utf-8").write("\n".join(out))
print({p: (len(c), sum(len(r) for r in c)) for p, c in planets.items()})
